import pandas as pd

# 1. 엑셀 파일 불러오기 (헤더 없이 통째로 가져오기 위해 header=None 설정)
file_path = "2025 서울시 구별 청년 1인가구수.xlsx"
df = pd.read_excel(file_path, header=None)

# -------------------------------------------------------------
# 2. 컬럼명(헤더) 재지정하기
# -------------------------------------------------------------
# 이미지 기준 3번째 행(인덱스 2)에 '20~24세', '25~29세' 등 실제 컬럼명이 있습니다.
# 0~1번 열은 자치구명, 2번 열은 성별('계', '남자', '여자')입니다.
df.columns = ['자치구1', '자치구', '성별', '20~24세', '25~29세', '30~34세', '35~39세']

# 데이터가 아닌 상단 헤더 3줄(2025, 합계, 연령대 행) 날리기
df = df.iloc[3:].reset_index(drop=True)

# -------------------------------------------------------------
# 3. 병합셀 비어있는 칸(NaN) 아래로 채우기 (Forward-fill)
# -------------------------------------------------------------
# 병합셀은 제일 첫 줄만 값이 들어가고 아래 2줄은 빈칸(NaN)이 됩니다.
# ffill()을 쓰면 위쪽의 구 이름('종로구', '중구' 등)을 빈칸에 똑같이 채워줍니다.
df['자치구'] = df['자치구'].ffill()

# -------------------------------------------------------------
# 4. 필요한 데이터만 필터링 (가공)
# -------------------------------------------------------------
# 조건 A: 서울시 전체 합계인 '소계' 행은 제외하고 순수 25개 자치구만 남기기
# 조건 B: 성별이 '계'인 행만 남기기 (남/여 합산 데이터)
df_clean = df[(df['자치구'] != '소계') & (df['성별'] == '계')].copy()

# -------------------------------------------------------------
# 5. 연령대 숫자 데이터 타입 변환 및 청년 1인가구 총합 계산
# -------------------------------------------------------------
age_cols = ['20~24세', '25~29세', '30~34세', '35~39세']

# 콤마(,)가 포함된 문자열일 수 있으므로 숫자로 변환합니다.
for col in age_cols:
    df_clean[col] = df_clean[col].astype(str).str.replace(',', '').astype(int)

# 20세~39세 전체 청년 1인가구수 합계 컬럼 만들기
df_clean['청년_1인가구수_총합'] = df_clean[age_cols].sum(axis=1)

# -------------------------------------------------------------
# 6. 최종 필요한 컬럼만 추출 및 저장
# -------------------------------------------------------------
result = df_clean[['자치구', '청년_1인가구수_총합', '20~24세', '25~29세', '30~34세', '35~39세']]

# 저장하기
result.to_csv("2025_서울시_자치구별_청년1인가구수_정제.csv", index=False, encoding='utf-8-sig')

print("전처리 완료!")
